export interface ReportDocumentSection {
  title: string
  columns: string[]
  rows: Array<Array<string | number | null | undefined>>
}

export interface ReportDocumentData {
  period: string
  generatedAt: string
  summary: Array<[string, string | number]>
  sections: ReportDocumentSection[]
}

const escapeHtml = (value: string | number | null | undefined): string => String(value ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;')

export function buildReportDocumentHtml(data: ReportDocumentData): string {
  const summaryRows = data.summary.map(([label, value]) => `<tr><th>${escapeHtml(label)}</th><td>${escapeHtml(value)}</td></tr>`).join('')
  const sections = data.sections.map((section) => {
    const header = section.columns.map((column) => `<th>${escapeHtml(column)}</th>`).join('')
    const rows = section.rows.length
      ? section.rows.map((row) => `<tr>${section.columns.map((_, index) => `<td>${escapeHtml(row[index])}</td>`).join('')}</tr>`).join('')
      : `<tr><td colspan="${Math.max(section.columns.length, 1)}">No records available.</td></tr>`
    return `<section><h2>${escapeHtml(section.title)}</h2><table><thead><tr>${header}</tr></thead><tbody>${rows}</tbody></table></section>`
  }).join('')

  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>SmartStock Reports</title><style>
    *{box-sizing:border-box}body{font:12px/1.45 Arial,sans-serif;color:#182230;margin:32px auto;max-width:1100px;padding:0 24px}header{border-bottom:3px solid #243b75;padding-bottom:16px;margin-bottom:20px}header .brand{font-size:11px;letter-spacing:.16em;text-transform:uppercase;color:#52627a;font-weight:bold}h1{font-size:25px;margin:5px 0}header p{margin:3px 0;color:#52627a}.summary{margin:18px 0 28px}.summary table{width:100%}h2{font-size:17px;margin:24px 0 8px;border-bottom:1px solid #cbd5e1;padding-bottom:5px}table{width:100%;border-collapse:collapse;table-layout:fixed;margin:8px 0 18px}th,td{border:1px solid #cbd5e1;padding:6px 8px;text-align:left;vertical-align:top;overflow-wrap:anywhere}thead th{background:#eef2f8;color:#172554}tbody tr:nth-child(even){background:#f8fafc}section{break-inside:auto}thead{display:table-header-group}tr{break-inside:avoid;page-break-inside:avoid}footer{border-top:1px solid #cbd5e1;padding-top:8px;margin-top:24px;color:#64748b;font-size:10px}@page{size:A4 landscape;margin:12mm}@media print{body{max-width:none;margin:0;padding:0}header{break-after:avoid}h2{break-after:avoid}}
    </style></head><body><header><div class="brand">SmartStock · Glassram Glass and Aluminum Supply</div><h1>Reports &amp; Sales Statement</h1><p><strong>Period:</strong> ${escapeHtml(data.period)}</p><p><strong>Generated:</strong> ${escapeHtml(data.generatedAt)}</p></header><section class="summary"><h2>Summary</h2><table><tbody>${summaryRows}</tbody></table></section>${sections}<footer>Generated by SmartStock. Report figures reflect recorded system data and selected filters.</footer></body></html>`
}

/** Print a generated report without relying on pop-up permissions or inline scripts. */
export function printReportDocument(html: string, documentRef: Document = document): Promise<void> {
  return new Promise((resolve, reject) => {
    const frame = documentRef.createElement('iframe')
    frame.title = 'SmartStock report print document'
    frame.setAttribute('aria-hidden', 'true')
    frame.tabIndex = -1
    frame.style.position = 'fixed'
    frame.style.left = '-10000px'
    frame.style.top = '0'
    frame.style.width = '100vw'
    frame.style.height = '100vh'
    frame.style.border = '0'

    let settled = false
    let cleanupTimer: ReturnType<typeof setTimeout> | undefined
    let loadTimer: ReturnType<typeof setTimeout>
    const cleanup = () => {
      if (cleanupTimer) clearTimeout(cleanupTimer)
      frame.remove()
    }
    const fail = (error: Error) => {
      if (settled) return
      settled = true
      clearTimeout(loadTimer)
      cleanup()
      reject(error)
    }
    loadTimer = setTimeout(() => fail(new Error('The print document did not finish loading.')), 15_000)

    frame.onerror = () => fail(new Error('The print document could not be loaded.'))
    frame.onload = () => {
      if (settled) return
      const printWindow = frame.contentWindow
      if (!printWindow) {
        fail(new Error('The browser could not open the print document.'))
        return
      }
      try {
        printWindow.addEventListener('afterprint', cleanup, { once: true })
        cleanupTimer = setTimeout(cleanup, 60_000)
        printWindow.focus()
        printWindow.print()
        settled = true
        clearTimeout(loadTimer)
        resolve()
      } catch (error) {
        fail(error instanceof Error ? error : new Error('The browser could not start printing.'))
      }
    }

    documentRef.body.appendChild(frame)
    frame.srcdoc = html
  })
}
